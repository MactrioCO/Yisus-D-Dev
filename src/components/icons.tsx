/** Icono según la red social elegida en el panel. */
export function socialIcon(id: string) {
  switch (id) {
    case "github": return GithubIcon;
    case "linkedin": return LinkedinIcon;
    case "x": return XIcon;
    case "youtube": return YoutubeIcon;
    case "instagram": return InstagramIcon;
    case "tiktok": return TikTokIcon;
    case "whatsapp": return WhatsAppIcon;
    case "facebook": return FacebookIcon;
    case "telegram": return TelegramIcon;
    case "discord": return DiscordIcon;
    case "twitch": return TwitchIcon;
    case "medium": return MediumIcon;
    case "email": return MailIcon;
    default: return GlobeIcon; // website / portfolio / desconocida
  }
}
